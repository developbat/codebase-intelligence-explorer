export function detectLanguage(relPath: string): string | null {
  const name = relPath.split("/").pop()?.toLowerCase() ?? "";
  if (SPECIAL_FILES[name]) return SPECIAL_FILES[name];
  if (name.startsWith("dockerfile.")) return "dockerfile";
  const dot = name.lastIndexOf(".");
  if (dot < 0) return null;
  const extension = name.slice(dot + 1);
  return EXTENSION_LANGUAGES[extension] ?? null;
}

export function isSupportedTextFile(relPath: string): boolean {
  return detectLanguage(relPath) !== null;
}
